"""Generate firmware/tinyfeat/src/tables.rs from the Python feature definitions.

    python scripts/gen_tinyfeat_tables.py

The Rust feature extractor cannot compute sin, cos or the band edges at build time on a
microcontroller without a maths library, and it must use exactly the Python definitions. This script
writes them out as constants:

* TWIDDLE_COS / TWIDDLE_SIN_NEG: cos(2 pi k / 1024) and -sin(2 pi k / 1024) for k in 0..512 (FFT twiddles)
* HANN_HALF: the first 512 points of numpy's symmetric Hann window np.hanning(1024); the rest follow by
  symmetry (the denominator is N-1, so it cannot be read off the twiddle table)
* BAND_EDGES: sustain_iq.signals.band_edges(513, 32), 33 bin-index edges

Values are rounded to f32, which is what the device uses, and written as the shortest decimal that
round-trips to the same f32. About 6 KB of flash.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sustain_iq.signals import N_BANDS, WINDOW, band_edges  # noqa: E402


def f32_list(a: np.ndarray) -> str:
    rows = []
    for i in range(0, len(a), 6):
        rows.append("    " + ", ".join(np.format_float_positional(np.float32(v), unique=True, trim="0") for v in a[i : i + 6]) + ",")
    return "\n".join(rows)


def main() -> None:
    n = WINDOW
    k = np.arange(n // 2)
    ang = 2 * np.pi * k / n
    hann = np.hanning(n)[: n // 2]
    edges = band_edges(n // 2 + 1, N_BANDS)
    assert len(edges) == N_BANDS + 1 and edges[0] == 1 and edges[-1] == n // 2 + 1

    out = f"""//! GENERATED by scripts/gen_tinyfeat_tables.py from sustain_iq.signals. Do not edit.

pub const TWIDDLE_COS: [f32; {n // 2}] = [
{f32_list(np.cos(ang))}
];

pub const TWIDDLE_SIN_NEG: [f32; {n // 2}] = [
{f32_list(-np.sin(ang))}
];

/// First half of `np.hanning({n})`; point `k >= {n // 2}` equals point `{n - 1} - k`.
pub const HANN_HALF: [f32; {n // 2}] = [
{f32_list(hann)}
];

/// Bin-index edges of the {N_BANDS} log-spaced bands: band `b` sums power bins `BAND_EDGES[b]..BAND_EDGES[b + 1]`.
pub const BAND_EDGES: [u16; {N_BANDS + 1}] = {[int(e) for e in edges]};
"""
    dest = ROOT / "firmware" / "tinyfeat" / "src" / "tables.rs"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {dest} ({dest.stat().st_size} bytes); band edges: {[int(e) for e in edges]}")


if __name__ == "__main__":
    main()
